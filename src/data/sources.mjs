export function groupSourcesByTier(sources = SOURCE_LIST) {
  return SOURCE_TIERS.map((tier) => ({
    ...tier,
    sources: sources.filter((source) =>
      tier.prefix
        ? source.credibility.startsWith(tier.prefix)
        : !SOURCE_TIERS.some((other) => other.prefix && source.credibility.startsWith(other.prefix))),
  })).filter((tier) => tier.sources.length > 0);
}
